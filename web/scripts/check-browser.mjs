import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ channel: process.platform === 'win32' ? 'msedge' : undefined, headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
await mkdir('screenshots', { recursive: true });
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
console.log('shelf', await page.locator('h1').textContent());
await page.screenshot({ path: 'screenshots/shelf-desktop.png', fullPage: true });
await page.goto('http://127.0.0.1:5173/#/sources', { waitUntil: 'networkidle' });
console.log('sources', await page.locator('.source-summary').innerText());
await page.screenshot({ path: 'screenshots/sources-desktop.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: 'screenshots/sources-mobile.png', fullPage: true });
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
await page.screenshot({ path: 'screenshots/shelf-mobile.png', fullPage: true });
console.log('errors', JSON.stringify(errors));
await browser.close();
if (errors.length) process.exitCode = 1;
